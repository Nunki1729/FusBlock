// Constructor
Piece::Piece(const int t, const int r) {
    type = t;
    rotation = r % 4;
    x = 0;
    y = 0;
}

// Rotación
void Piece::rotate() {
    rotation = (rotation + 1) % 4;
}

// Getters
int Piece::getX() const {
    return x;
}

int Piece::getY() const {
    return y;
}

int Piece::getType() const {
    return type;
}

int Piece::getRotation() const {
    return rotation;
}

bool Piece::getCell(int i, int j) const {
    return shapes[type][rotation][i][j];
}

// Movimientos
void Piece::move_left() {
    if (x > 0) {
        x--;
    }
}

void Piece::move_right() {
    if (x < 12) {
        x++;
    }
}

void Piece::fall() {
    y++;
}

// Mostrar
void Piece::show() {
    for (int i = 0; i < 4; i++) {
        for (int j = 0; j < 4; j++) {
            std::cout << shapes[type][rotation][i][j] << " ";
        }
        std::cout << std::endl;
    }
} 